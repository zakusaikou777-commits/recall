/** 実行中のバージョン（manifest.json が原本） */
export function currentVersion() {
  try { return chrome.runtime.getManifest().version; } catch { return CHANGELOG[0].v; }
}

export function entryFor(version) {
  return CHANGELOG.find(e => e.v === version) || null;
}
